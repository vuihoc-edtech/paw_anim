/// Dữ liệu cấu hình đường bay của mỗi chân mèo (paw flight).
class PawFlightData {
  final int mx;
  final int my;
  final int fx;
  final int fy;
  final double r;
  final double s;
  final int d;

  const PawFlightData({
    required this.mx,
    required this.my,
    required this.fx,
    required this.fy,
    required this.r,
    required this.s,
    required this.d,
  });
}
